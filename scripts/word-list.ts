// Writes docs/word-list.md: the word bank grouped by the letter from which each
// word is allowed, for the parent to approve. Run with `npm run word-list`.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { analyzeWord, graphemeOrder } from '../src/engine/allowedWords.ts';
import type { Curriculum, Word } from '../src/engine/types.ts';

const root = join(import.meta.dirname, '..');
const read = <T>(file: string): T => JSON.parse(readFileSync(join(root, 'src', 'content', file), 'utf8')) as T;

const curriculum = read<Curriculum>('curriculum.json');
const order = graphemeOrder(curriculum);
const words = read<Word[]>('words.json').map((w) => analyzeWord(w, order));

const lines: string[] = [
  '# Word list for approval',
  '',
  'Generated by `npm run word-list` from `src/content/words.json`. Do not edit by hand.',
  '',
  'Strike out (or tell Claude) any word to drop or change. Words with flags stay hidden until the parent unlocks that flag.',
  '',
  `${words.length} words, ${words.filter((w) => w.flags.length === 0).length} without flags.`,
  '',
];

for (const unit of curriculum.units.filter((u) => u.graphemes.length > 0)) {
  const start = order.unitStart.get(unit.id)!;
  const inUnit = words.filter((w) => w.minPosition > start && w.minPosition <= start + unit.graphemes.length);
  if (inUnit.length === 0) continue;
  lines.push(`## ${unit.title}`, '');
  for (const g of unit.graphemes) {
    const atLetter = inUnit.filter((w) => w.minPosition === order.positionOf.get(g));
    if (atLetter.length === 0) continue;
    lines.push(`**from «${g}»**`, '');
    lines.push('| | Word | Syllables | Flags | Category | Image |', '| --- | --- | --- | --- | --- | --- |');
    for (const w of atLetter) {
      const article = w.article ? `${w.article} ` : '';
      lines.push(`| [ ] | ${article}${w.text} | ${w.syllables.join('-')} | ${w.flags.join(', ') || '–'} | ${w.category} | ${w.imageId ?? ''} |`);
    }
    lines.push('');
  }
}

const unusable = words.filter((w) => !Number.isFinite(w.minPosition));
if (unusable.length) lines.push('## Not in curriculum', '', ...unusable.map((w) => `- ${w.text}`), '');

mkdirSync(join(root, 'docs'), { recursive: true });
writeFileSync(join(root, 'docs', 'word-list.md'), lines.join('\n'));
console.log(`docs/word-list.md: ${words.length} words`);
